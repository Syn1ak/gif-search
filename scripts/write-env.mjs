// Writes src/environments/environment.generated.ts from the GIPHY_API_KEY environment variable.
// Run through `npm run env`, which loads `.env` (if present) via `node --env-file-if-exists`.
import { writeFileSync } from 'node:fs';

const apiKey = process.env.GIPHY_API_KEY?.trim() ?? '';
const target = new URL('../src/environments/environment.generated.ts', import.meta.url);

if (!apiKey) {
  console.warn(
    '[env] GIPHY_API_KEY is not set. Copy .env.example to .env and add your key; ' +
      'until then the app shows the "invalid API key" state.',
  );
}

writeFileSync(
  target,
  `// Generated by scripts/write-env.mjs. Do not edit or commit.
export const GENERATED_ENV = {
  giphyApiKey: ${JSON.stringify(apiKey)},
} as const;
`,
);
